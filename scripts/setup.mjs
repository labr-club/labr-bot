#!/usr/bin/env node
// npm run setup: gets a new Labr running with as few steps as possible.
//
// The only thing it can't do for you is create the Discord bot (Discord has no
// API for that). Everything else is checked or filled in here: the bot's
// privileged intents, your Discord user ID, the encryption key, the invite link
// with the right permissions, and which server the bot is allowed in.
//
// Keys go into .env on this machine only. Nothing is sent anywhere except to
// the service each key belongs to (Discord, Anthropic, Quidli Connect), to check it.

import { createInterface } from 'node:readline/promises';
import { existsSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { spawnSync, spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ENV_PATH = join(ROOT, '.env');
const DISCORD_API = 'https://discord.com/api/v10';
const CONNECT_MCP = 'https://mcp.connect.quid.li/';

// ─── Pure helpers (tested) ────────────────────────────────────────────────────

// Application flags for privileged intents. Bots in under 100 servers use the
// _LIMITED flags, which are also the only ones an app can set on itself.
export const INTENTS = [
  { name: 'Message Content', full: 1 << 18, limited: 1 << 19 },
  { name: 'Server Members', full: 1 << 14, limited: 1 << 15 },
  { name: 'Presence', full: 1 << 12, limited: 1 << 13 },
];
export function missingIntents(flags) {
  return INTENTS.filter((i) => !(flags & i.full) && !(flags & i.limited));
}

// View Channels, Send Messages, Manage Messages (deletes keys posted in a
// channel), Embed Links, Attach Files, Read Message History, Manage Roles
// (token access gives and removes the holder role).
export const BOT_PERMISSIONS = (1n << 10n) | (1n << 11n) | (1n << 13n) | (1n << 14n) | (1n << 15n) | (1n << 16n) | (1n << 28n);
export function inviteUrl(appId) {
  return `https://discord.com/oauth2/authorize?client_id=${appId}&scope=bot&permissions=${BOT_PERMISSIONS}`;
}

export const looksUnset = (v) => !v || /^your_.*_here$/.test(String(v).trim());

export function parseEnv(text) {
  const out = new Map();
  for (const line of String(text ?? '').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m) out.set(m[1], m[2].trim().replace(/^(['"])(.*)\1$/, '$2'));
  }
  return out;
}

// What a Labr instance needs, in the order it's written. Anything else already
// in .env is kept below it untouched.
const LABR_KEYS = [
  ['DISCORD_TOKEN', 'Discord bot token'],
  ['ANTHROPIC_API_KEY', 'Anthropic API key'],
  ['QUIDLI_API_KEY', 'Quidli Connect API key (the host key; members link their own with !connect)'],
  ['MASTER_ENCRYPTION_KEY', 'Encrypts the keys members link. Generated by setup; keep it, or linked keys stop working.'],
  ['BOT_OWNER_ID', 'Your Discord user ID (read from the bot\'s owner)'],
  ['DISCORD_ALLOWED_GUILDS', 'The only server the bot stays in'],
  ['SYSTEM_PROMPT_FILE', 'Labr\'s instructions'],
  ['OWNER_USES_HOST_KEY', 'false = you pay from your own linked key like everyone else'],
];
export function renderEnv(values, existing = new Map()) {
  const lines = ['# Written by `npm run setup`. Every other option is in .env.example.', ''];
  for (const [k, note] of LABR_KEYS) {
    const v = values[k] ?? existing.get(k);
    if (v === undefined || v === '') continue;
    lines.push(`# ${note}`, `${k}=${v}`, '');
  }
  const rest = [...existing].filter(([k]) => !LABR_KEYS.some(([lk]) => lk === k) && !looksUnset(existing.get(k)));
  if (rest.length) {
    lines.push('# Kept from your previous .env');
    for (const [k, v] of rest) lines.push(`${k}=${v}`);
    lines.push('');
  }
  return lines.join('\n');
}

// ─── Checks against each service ──────────────────────────────────────────────

export async function checkDiscord(token, fetchImpl = fetch) {
  const res = await fetchImpl(`${DISCORD_API}/applications/@me`, { headers: { authorization: `Bot ${token}` } });
  if (res.status === 401) return { ok: false, why: 'Discord rejected this token. Copy it again from the Bot page (Reset Token).' };
  if (!res.ok) return { ok: false, why: `Discord answered ${res.status}. Try again in a minute.` };
  const app = await res.json();
  const ownerId = app.team?.owner_user_id ?? app.owner?.id ?? null;
  return { ok: true, appId: app.id, name: app.name, ownerId, flags: Number(app.flags ?? 0) };
}

/** Turns on the privileged intents the bot needs. Returns the ones still missing. */
export async function enableIntents(token, flags, fetchImpl = fetch) {
  const missing = missingIntents(flags);
  if (!missing.length) return [];
  const limitedMask = INTENTS.reduce((m, i) => m | i.limited, 0);
  const want = (flags & limitedMask) | missing.reduce((m, i) => m | i.limited, 0);
  try {
    await fetchImpl(`${DISCORD_API}/applications/@me`, {
      method: 'PATCH',
      headers: { authorization: `Bot ${token}`, 'content-type': 'application/json' },
      body: JSON.stringify({ flags: want }),
    });
  } catch { /* checked below */ }
  const again = await checkDiscord(token, fetchImpl);
  return again.ok ? missingIntents(again.flags) : missing;
}

export async function checkAnthropic(key, fetchImpl = fetch) {
  const res = await fetchImpl('https://api.anthropic.com/v1/models?limit=1', {
    headers: { 'x-api-key': key, 'anthropic-version': '2023-06-01' },
  });
  if (res.status === 401 || res.status === 403) return { ok: false, why: 'Anthropic rejected this key.' };
  if (!res.ok) return { ok: false, why: `Anthropic answered ${res.status}. Try again in a minute.` };
  return { ok: true };
}

async function connectTool(key, name, args, fetchImpl) {
  const res = await fetchImpl(CONNECT_MCP, {
    method: 'POST',
    headers: { 'x-api-key': key, 'content-type': 'application/json', accept: 'application/json, text/event-stream' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name, arguments: args } }),
  });
  if (res.status === 401 || res.status === 403) return { ok: false, auth: true };
  if (!res.ok) return { ok: false, why: `Connect answered ${res.status}` };
  const body = await res.json();
  const text = (body.result?.content ?? []).filter((c) => c.type === 'text').map((c) => c.text).join('\n');
  if (body.error || body.result?.isError) return { ok: false, why: body.error?.message ?? text.slice(0, 200) };
  try { return { ok: true, data: JSON.parse(text) }; } catch { return { ok: true, data: null }; }
}

export async function checkConnect(key, fetchImpl = fetch) {
  const me = await connectTool(key, 'connect_me', {}, fetchImpl);
  if (me.auth) return { ok: false, why: 'Connect rejected this key. Create one at https://connect.quid.li (API keys).' };
  if (!me.ok) return { ok: false, why: me.why ?? 'Connect did not answer. Try again in a minute.' };
  const bal = await connectTool(key, 'connect_drop_balance', { chainId: 8453 }, fetchImpl);
  return {
    ok: true,
    username: me.data?.profile?.username ?? null,
    smartSendWallet: bal.ok ? (bal.data?.walletAddress ?? null) : null,
  };
}

export async function botGuilds(token, fetchImpl = fetch) {
  const res = await fetchImpl(`${DISCORD_API}/users/@me/guilds`, { headers: { authorization: `Bot ${token}` } });
  if (!res.ok) return [];
  return (await res.json()).map((g) => ({ id: g.id, name: g.name }));
}

// ─── The wizard ───────────────────────────────────────────────────────────────

const b = (s) => `\x1b[1m${s}\x1b[0m`;
const ok = (s) => console.log(`  \x1b[32m✓\x1b[0m ${s}`);
const bad = (s) => console.log(`  \x1b[31m✗\x1b[0m ${s}`);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// One question per readline interface, closed right after, so nothing is left
// listening to stdin while a key is typed.
async function ask(q, def = '') {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  try { return (await rl.question(`${q}${def ? ` [${def}]` : ''}: `)).trim() || def; }
  finally { rl.close(); }
}

// Keys are read in raw mode: the label stays on screen and each character shows
// as a dot, so a paste visibly lands. Without a terminal (piped input) it falls
// back to a plain line read.
export function readHidden(prompt, { input = process.stdin, output = process.stdout } = {}) {
  if (!input.isTTY) return ask(prompt);
  output.write(`${prompt}: `);
  return new Promise((resolve) => {
    let buf = '';
    const done = () => {
      input.off('data', onData);
      input.setRawMode(false);
      input.pause();
      output.write('\n');
      resolve(buf.trim());
    };
    const onData = (chunk) => {
      for (const ch of chunk.toString('utf8')) {
        if (ch === '\r' || ch === '\n') return done();
        if (ch === '\u0003') { output.write('\n'); process.exit(130); }
        if (ch === '\u007f' || ch === '\b') {
          if (buf) { buf = buf.slice(0, -1); output.write('\b \b'); }
          continue;
        }
        if (ch < ' ') continue;
        buf += ch;
        output.write('•');
      }
    };
    input.setRawMode(true);
    input.resume();
    input.on('data', onData);
  });
}

async function askSecret(q, current) {
  const hint = looksUnset(current) ? '' : ` [Enter keeps …${String(current).slice(-4)}]`;
  const a = await readHidden(`${q}${hint}`);
  return a || (looksUnset(current) ? '' : current);
}

async function main() {
  const [major] = process.versions.node.split('.').map(Number);
  if (major < 22) { console.error(`Labr needs Node 22 or newer (this is ${process.versions.node}).`); process.exit(1); }


  const existing = existsSync(ENV_PATH) ? parseEnv(readFileSync(ENV_PATH, 'utf8')) : new Map();
  const v = {};

  console.log(`\n${b('Labr setup')}  (about 5 minutes)\n`);

  // 1. Discord
  console.log(`${b('1/4 Discord bot')}`);
  console.log('  Create one at https://discord.com/developers/applications');
  console.log('  New Application → Bot → Reset Token → copy the token.\n');
  let discord;
  for (;;) {
    v.DISCORD_TOKEN = await askSecret('  Bot token', existing.get('DISCORD_TOKEN'));
    if (!v.DISCORD_TOKEN) continue;
    discord = await checkDiscord(v.DISCORD_TOKEN);
    if (discord.ok) break;
    bad(discord.why);
  }
  ok(`Bot "${discord.name}" (${discord.appId})`);
  const stillMissing = await enableIntents(v.DISCORD_TOKEN, discord.flags);
  if (stillMissing.length) {
    bad(`Turn on ${stillMissing.map((i) => i.name).join(', ')} under Bot → Privileged Gateway Intents:`);
    console.log(`    https://discord.com/developers/applications/${discord.appId}/bot`);
    for (;;) {
      await ask('  Press Enter once they are on');
      const again = await checkDiscord(v.DISCORD_TOKEN);
      const left = again.ok ? missingIntents(again.flags) : stillMissing;
      if (!left.length) break;
      bad(`Still off: ${left.map((i) => i.name).join(', ')}`);
    }
  }
  ok('Message Content, Server Members and Presence are on');
  if (discord.ownerId) { v.BOT_OWNER_ID = discord.ownerId; ok(`You are the owner (${discord.ownerId})`); }

  // 2. Anthropic
  console.log(`\n${b('2/4 AI key')}`);
  console.log('  Get one at https://console.anthropic.com (API Keys).\n');
  for (;;) {
    v.ANTHROPIC_API_KEY = await askSecret('  Anthropic API key', existing.get('ANTHROPIC_API_KEY'));
    if (!v.ANTHROPIC_API_KEY) continue;
    const r = await checkAnthropic(v.ANTHROPIC_API_KEY);
    if (r.ok) { ok('Key works'); break; }
    bad(r.why);
  }

  // 3. Connect
  console.log(`\n${b('3/4 Quidli Connect')}`);
  console.log('  Sign in at https://connect.quid.li, create an API key, and turn on Smart Send.\n');
  for (;;) {
    v.QUIDLI_API_KEY = await askSecret('  Connect API key', existing.get('QUIDLI_API_KEY'));
    if (!v.QUIDLI_API_KEY) continue;
    const r = await checkConnect(v.QUIDLI_API_KEY);
    if (!r.ok) { bad(r.why); continue; }
    ok(`Connected as ${r.username ?? 'your account'}`);
    if (r.smartSendWallet) ok(`Sends come from ${r.smartSendWallet}. Fund it with what you'll pay out (gas is sponsored on Base).`);
    else bad('Smart Send looks off. Turn it on at https://connect.quid.li → Smart Send before the bot pays anyone.');
    break;
  }

  v.MASTER_ENCRYPTION_KEY = looksUnset(existing.get('MASTER_ENCRYPTION_KEY')) ? randomBytes(32).toString('hex') : existing.get('MASTER_ENCRYPTION_KEY');
  v.SYSTEM_PROMPT_FILE = 'labr-prompt.txt';
  v.OWNER_USES_HOST_KEY = existing.get('OWNER_USES_HOST_KEY') || 'false';

  if (existsSync(ENV_PATH)) {
    const bak = `${ENV_PATH}.backup-${Date.now()}`;
    copyFileSync(ENV_PATH, bak);
    console.log(`\n  (Your previous .env is saved as ${bak.split('/').pop()})`);
  }
  writeFileSync(ENV_PATH, renderEnv(v, existing), { mode: 0o600 });

  // 4. Server
  console.log(`\n${b('4/4 Add the bot to your server')}`);
  console.log(`  Open this link and pick your server:\n\n  ${inviteUrl(discord.appId)}\n`);
  let guilds = await botGuilds(v.DISCORD_TOKEN);
  if (!guilds.length) {
    process.stdout.write('  Waiting for the bot to join');
    for (let i = 0; i < 100 && !guilds.length; i++) { await sleep(3000); process.stdout.write('.'); guilds = await botGuilds(v.DISCORD_TOKEN); }
    process.stdout.write('\n');
  }
  if (!guilds.length) {
    bad('The bot has not joined a server yet. Run `npm run setup` again after adding it; your answers are saved.');
  } else {
    let g = guilds[0];
    if (guilds.length > 1) {
      guilds.forEach((x, i) => console.log(`    ${i + 1}. ${x.name}`));
      const pick = Number(await ask('  Which server is Labr for?', '1'));
      g = guilds[Math.max(1, Math.min(guilds.length, pick || 1)) - 1];
    }
    v.DISCORD_ALLOWED_GUILDS = g.id;
    writeFileSync(ENV_PATH, renderEnv(v, existing), { mode: 0o600 });
    ok(`In "${g.name}". The bot will leave any other server it's added to.`);
  }

  console.log(`\n${b('Done.')} Settings are in .env (only on this machine).`);
  const hasPm2 = spawnSync('pm2', ['-v'], { stdio: 'ignore' }).status === 0;
  const start = (await ask(`  Start Labr now${hasPm2 ? ' with pm2 (keeps running after you close this)' : ''}? (Y/n)`, 'Y')).toLowerCase();
  if (start.startsWith('n')) {
    console.log(`\n  Start it later with ${hasPm2 ? '`pm2 start labr.config.cjs && pm2 save`' : '`npm start`'}.`);
  } else if (hasPm2) {
    spawnSync('pm2', ['start', 'labr.config.cjs'], { cwd: ROOT, stdio: 'inherit' });
    spawnSync('pm2', ['save'], { cwd: ROOT, stdio: 'inherit' });
    console.log('\n  Logs: `pm2 logs labr`');
  } else {
    console.log('\n  Starting in this window. Close it and the bot stops; for always-on, `npm i -g pm2` then `pm2 start labr.config.cjs`.\n');
    spawn('node', ['bot.js'], { cwd: ROOT, stdio: 'inherit' });
    return;
  }
  console.log(`\n  In your server, say ${b('@' + discord.name + ' help')}. Everyone links their own wallet by DMing the bot ${b('!connect <key>')}.\n`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((err) => { console.error(`\nSetup stopped: ${err.message}`); process.exit(1); });
}
