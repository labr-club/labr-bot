export async function checkDiscord(token, fetchImpl = fetch) {
  const res = await fetchImpl(`${DISCORD_API}/applications/@me`, { headers: { authorization: `Bot ${token}` } });
  if (res.status === 401) return { ok: false, why: 'Discord rejected this token. Copy it again from the Bot page (Reset Token).' };
  if (!res.ok) return { ok: false, why: `Discord answered ${res.status}. Try again in a minute.` };
  const app = await res.json();
  const ownerId = app.team?.owner_user_id ?? app.owner?.id ?? null;
  return { ok: true, appId: app.id, name: app.name, ownerId, flags: Number(app.flags ?? 0) };
}

/** Turns on the privileged intents the bot needs. Returns the ones still missing. */
export async function enableIntents(token, flags, fetchImpl = fetch) {
  const missing = missingIntents(flags);
  if (!missing.length) return [];
  const limitedMask = INTENTS.reduce((m, i) => m | i.limited, 0);
  const want = (flags & limitedMask) | missing.reduce((m, i) => m | i.limited, 0);
  try {
    await fetchImpl(`${DISCORD_API}/applications/@me`, {
      method: 'PATCH',
      headers: { authorization: `Bot ${token}`, 'content-type': 'application/json' },
      body: JSON.stringify({ flags: want }),
    });
  } catch { /* checked below */ }
  const again = await checkDiscord(token, fetchImpl);
  return again.ok ? missingIntents(again.flags) : missing;
}

// A real one-token request with the bot's default model, not just a key lookup:
// listing models works on an account with no credit, and the bot would then
// fail on its first message. Costs a fraction of a cent.
export const CHECK_MODEL = 'claude-sonnet-4-6';
export async function checkAnthropic(key, fetchImpl = fetch) {
  const res = await fetchImpl('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'x-api-key': key, 'anthropic-version': '2023-06-01', 'content-type': 'application/json' },
    body: JSON.stringify({ model: CHECK_MODEL, max_tokens: 1, messages: [{ role: 'user', content: 'hi' }] }),
  });
  if (res.ok) return { ok: true };
  let msg = '';
  try { msg = String((await res.json())?.error?.message ?? ''); } catch { /* no body */ }
  if (res.status === 401) return { ok: false, why: 'Anthropic rejected this key.' };
  if (/credit balance/i.test(msg)) {
    return { ok: false, noCredit: true, why: 'This key works, but the account has no credit. Add some at https://console.anthropic.com/settings/billing' };
  }
  if (res.status === 403) return { ok: false, why: `This key can't use ${CHECK_MODEL}. ${msg}`.trim() };
  if (res.status === 429 || res.status === 529) return { ok: true, busy: true }; // the key is fine; Anthropic is busy
  return { ok: false, why: `Anthropic answered ${res.status}${msg ? `: ${msg}` : ''}. Try again in a minute.` };
}

// OpenAI and Nous Portal speak the same API.
export async function checkOpenAICompatible({ baseURL, key, model, billing }, fetchImpl = fetch) {
  const res = await fetchImpl(`${baseURL}/chat/completions`, {
    method: 'POST',
    headers: { authorization: `Bearer ${key}`, 'content-type': 'application/json' },
    body: JSON.stringify({ model, max_tokens: 1, messages: [{ role: 'user', content: 'hi' }] }),
  });
  if (res.ok) return { ok: true };
  let err = {};
  try { err = (await res.json())?.error ?? {}; } catch { /* no body */ }
  const msg = String(err.message ?? '');
  if (res.status === 401) return { ok: false, why: 'This key was rejected.' };
  if (err.code === 'insufficient_quota' || /quota|credit|billing|balance/i.test(msg)) {
    return { ok: false, noCredit: true, why: `This key works, but the account has no credit. Add some at ${billing}` };
  }
  if (res.status === 404 || err.code === 'model_not_found') return { ok: false, why: `This key can't use ${model}. ${msg}`.trim() };
  if (res.status === 429 || res.status >= 500) return { ok: true, busy: true };
  return { ok: false, why: `The provider answered ${res.status}${msg ? `: ${msg}` : ''}.` };
}

// Gemini: list the models this key can use, pick a Flash model, then make a
// one-token request with it (that is where a missing quota shows up).
export async function checkGemini(key, preferred, fetchImpl = fetch) {
  const base = 'https://generativelanguage.googleapis.com/v1beta';
  const list = await fetchImpl(`${base}/models?key=${encodeURIComponent(key)}&pageSize=200`);
  if (list.status === 400 || list.status === 401 || list.status === 403) return { ok: false, why: 'Google rejected this key.' };
  if (!list.ok) return { ok: false, why: `Google answered ${list.status}. Try again in a minute.` };
  const names = ((await list.json()).models ?? [])
    .filter((m) => (m.supportedGenerationMethods ?? []).includes('generateContent'))
    .map((m) => String(m.name).replace(/^models\//, ''));
  const model = [preferred, 'gemini-2.5-flash'].find((m) => m && names.includes(m))
    ?? names.find((n) => /^gemini-[\d.]+-flash$/.test(n)) ?? names.find((n) => /flash/.test(n));
  if (!model) return { ok: false, why: 'This key has no Gemini model it can use.' };
  const res = await fetchImpl(`${base}/models/${model}:generateContent?key=${encodeURIComponent(key)}`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ contents: [{ parts: [{ text: 'hi' }] }], generationConfig: { maxOutputTokens: 1 } }),
  });
  if (res.ok || res.status === 429 || res.status >= 500) return { ok: true, model, busy: !res.ok };
  let msg = '';
  try { msg = String((await res.json())?.error?.message ?? ''); } catch { /* no body */ }
  return { ok: false, why: `Google answered ${res.status}${msg ? `: ${msg}` : ''}.` };
}

// Nous Portal retires free models without notice, so setup reads the live list
// and uses the first model that both exists and answers a tool call (Labr
// can't look anyone up or pay without tools).
const NOUS = 'https://inference-api.nousresearch.com/v1';
const TOOL_PROBE = [{ type: 'function', function: { name: 'ping', description: 'Reply with ok', parameters: { type: 'object', properties: { ok: { type: 'boolean' } }, required: ['ok'] } } }];
export async function checkNous(key, preferred, fetchImpl = fetch) {
  const list = await fetchImpl(`${NOUS}/models`);
  if (!list.ok) return { ok: false, why: `Nous Portal answered ${list.status}. Try again in a minute.` };
  const models = (await list.json()).data ?? [];
  const toolCapable = (m) => (m.supported_parameters ?? []).includes('tools');
  const ids = new Set(models.map((m) => m.id));
  const candidates = [
    ...(preferred && ids.has(preferred) ? [preferred] : []),
    ...models.filter((m) => m.id.endsWith(':free') && toolCapable(m)).map((m) => m.id),
  ].filter((id, i, a) => a.indexOf(id) === i);
  if (!candidates.length) return { ok: false, why: 'Nous Portal lists no free model that supports tools right now. Set NOUS_MODEL to a paid one in .env.' };
  for (const model of candidates) {
    const res = await fetchImpl(`${NOUS}/chat/completions`, {
      method: 'POST',
      headers: { authorization: `Bearer ${key}`, 'content-type': 'application/json' },
      body: JSON.stringify({ model, max_tokens: 50, messages: [{ role: 'user', content: 'Call ping.' }], tools: TOOL_PROBE }),
    });
    if (res.status === 401) return { ok: false, why: 'This key was rejected.' };
    let body = {};
    try { body = await res.json(); } catch { /* no body */ }
    const msg = String(body?.error?.message ?? body?.message ?? '');
    if (/quota|credit|balance/i.test(msg)) return { ok: false, noCredit: true, why: `This key works, but the account has no credit. Add some at https://portal.nousresearch.com` };
    if (res.ok && body.choices) return { ok: true, model };
  }
  return { ok: false, why: `None of these models answered a tool call: ${candidates.join(', ')}. Try again later, or set NOUS_MODEL in .env.` };
}

