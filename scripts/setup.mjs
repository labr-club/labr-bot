// Application flags for privileged intents. Bots in under 100 servers use the
// _LIMITED flags, which are also the only ones an app can set on itself.
export const INTENTS = [
  { name: 'Message Content', full: 1 << 18, limited: 1 << 19 },
  { name: 'Server Members', full: 1 << 14, limited: 1 << 15 },
  { name: 'Presence', full: 1 << 12, limited: 1 << 13 },
];
export function missingIntents(flags) {
  return INTENTS.filter((i) => !(flags & i.full) && !(flags & i.limited));
}

// View Channels, Send Messages, Manage Messages (deletes keys posted in a
// channel), Embed Links, Attach Files, Read Message History, Manage Roles
// (token access gives and removes the holder role).
export const BOT_PERMISSIONS = (1n << 10n) | (1n << 11n) | (1n << 13n) | (1n << 14n) | (1n << 15n) | (1n << 16n) | (1n << 28n);
export function inviteUrl(appId) {
  return `https://discord.com/oauth2/authorize?client_id=${appId}&scope=bot&permissions=${BOT_PERMISSIONS}`;
}

