/** Checks a key for the chosen provider. Gemini also returns the model to use. */
export async function checkProvider(id, key, env = {}, fetchImpl = fetch) {
  if (id === 'anthropic') return checkAnthropic(key, fetchImpl);
  if (id === 'openai') return checkOpenAICompatible({ baseURL: 'https://api.openai.com/v1', key, model: env.OPENAI_MODEL || 'gpt-4o', billing: 'https://platform.openai.com/settings/organization/billing' }, fetchImpl);
  if (id === 'hermes') return checkNous(key, env.NOUS_MODEL, fetchImpl);
  if (id === 'gemini') return checkGemini(key, env.GEMINI_MODEL, fetchImpl);
  return { ok: false, why: `unknown provider ${id}` };
}

async function connectTool(key, name, args, fetchImpl) {
  const res = await fetchImpl(CONNECT_MCP, {
    method: 'POST',
    headers: { 'x-api-key': key, 'content-type': 'application/json', accept: 'application/json, text/event-stream' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name, arguments: args } }),
  });
  if (res.status === 401 || res.status === 403) return { ok: false, auth: true };
  if (!res.ok) return { ok: false, why: `Connect answered ${res.status}` };
  const body = await res.json();
  const text = (body.result?.content ?? []).filter((c) => c.type === 'text').map((c) => c.text).join('\n');
  if (body.error || body.result?.isError) return { ok: false, why: body.error?.message ?? text.slice(0, 200) };
  try { return { ok: true, data: JSON.parse(text) }; } catch { return { ok: true, data: null }; }
}

// Solana sends cost the sender a small fee, and paying a token to someone for
// the first time opens their token account (about 0.002 SOL). Below this, warn.
export const MIN_SOL_LAMPORTS = 10_000_000n; // 0.01 SOL

export async function checkConnect(key, fetchImpl = fetch, chain = CHAINS.base) {
  const me = await connectTool(key, 'connect_me', {}, fetchImpl);
  if (me.auth) return { ok: false, why: 'Connect rejected this key. Create one at https://connect.quid.li (API keys).' };
  if (!me.ok) return { ok: false, why: me.why ?? 'Connect did not answer. Try again in a minute.' };
  const bal = await connectTool(key, 'connect_drop_balance', { chainId: chain.id }, fetchImpl);
  const native = bal.ok ? (bal.data?.assets ?? []).find((a) => a.type === 'native') : null;
  let lowGas = false;
  try {
    const have = BigInt(native?.balanceInWei ?? 0);
    lowGas = !chain.sponsored && bal.ok && (chain.id === CHAINS.solana.id ? have < MIN_SOL_LAMPORTS : have === 0n);
  } catch { lowGas = true; }
  return {
    ok: true,
    username: me.data?.profile?.username ?? null,
    smartSendWallet: bal.ok ? (bal.data?.walletAddress ?? null) : null,
    lowGas,
  };
}

// The chains to offer: Labr's known chains that Connect sends on right now,
// Base first, then Solana, then the rest. If Connect can't be asked, all of them.
export async function chainChoices(key, fetchImpl = fetch) {
  const all = Object.entries(CHAINS).map(([slug, c]) => ({ slug, ...c }));
  const r = await connectTool(key, 'connect_get_chains', {}, fetchImpl).catch(() => ({ ok: false }));
  const live = r.ok && Array.isArray(r.data?.chains) ? r.data.chains.filter((c) => !c.isTestnet && c.features?.drop !== false).map((c) => Number(c.chainId)) : null;
  return live?.length ? all.filter((c) => live.includes(c.id)) : all;
}

