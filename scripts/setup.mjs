// ─── The wizard ───────────────────────────────────────────────────────────────

const b = (s) => `\x1b[1m${s}\x1b[0m`;
const ok = (s) => console.log(`  \x1b[32m✓\x1b[0m ${s}`);
const bad = (s) => console.log(`  \x1b[31m✗\x1b[0m ${s}`);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// One question per readline interface, closed right after, so nothing is left
// listening to stdin while a key is typed.
async function ask(q, def = '') {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  try { return (await rl.question(`${q}${def ? ` [${def}]` : ''}: `)).trim() || def; }
  finally { rl.close(); }
}

// Keys are read in raw mode: the label stays on screen and each character shows
// as a dot, so a paste visibly lands. Without a terminal (piped input) it falls
// back to a plain line read.
export function readHidden(prompt, { input = process.stdin, output = process.stdout } = {}) {
  if (!input.isTTY) return ask(prompt);
  output.write(`${prompt}: `);
  return new Promise((resolve) => {
    let buf = '';
    const done = () => {
      input.off('data', onData);
      input.setRawMode(false);
      input.pause();
      output.write('\n');
      resolve(buf.trim());
    };
    const onData = (chunk) => {
      for (const ch of chunk.toString('utf8')) {
        if (ch === '\r' || ch === '\n') return done();
        if (ch === '\u0003') { output.write('\n'); process.exit(130); }
        if (ch === '\u007f' || ch === '\b') {
          if (buf) { buf = buf.slice(0, -1); output.write('\b \b'); }
          continue;
        }
        if (ch < ' ') continue;
        buf += ch;
        output.write('•');
      }
    };
    input.setRawMode(true);
    input.resume();
    input.on('data', onData);
  });
}

async function askSecret(q, current) {
  const hint = looksUnset(current) ? '' : ` [Enter keeps …${String(current).slice(-4)}]`;
  const a = await readHidden(`${q}${hint}`);
  return a || (looksUnset(current) ? '' : current);
}

async function main() {
  const [major] = process.versions.node.split('.').map(Number);
  if (major < 22) { console.error(`Labr needs Node 22 or newer (this is ${process.versions.node}).`); process.exit(1); }


  const existing = existsSync(ENV_PATH) ? parseEnv(readFileSync(ENV_PATH, 'utf8')) : new Map();
  const v = {};

  console.log(`\n${b('Labr setup')}  (about 5 minutes)\n`);

  // 1. Discord
  console.log(`${b('1/4 Discord bot')}`);
  console.log('  Create one at https://discord.com/developers/applications');
  console.log('  New Application → Bot → Reset Token → copy the token.\n');
  let discord;
  for (;;) {
    v.DISCORD_TOKEN = await askSecret('  Bot token', existing.get('DISCORD_TOKEN'));
    if (!v.DISCORD_TOKEN) continue;
    discord = await checkDiscord(v.DISCORD_TOKEN);
    if (discord.ok) break;
    bad(discord.why);
  }
  ok(`Bot "${discord.name}" (${discord.appId})`);
  const stillMissing = await enableIntents(v.DISCORD_TOKEN, discord.flags);
  if (stillMissing.length) {
    bad(`Turn on ${stillMissing.map((i) => i.name).join(', ')} under Bot → Privileged Gateway Intents:`);
    console.log(`    https://discord.com/developers/applications/${discord.appId}/bot`);
    for (;;) {
      await ask('  Press Enter once they are on');
      const again = await checkDiscord(v.DISCORD_TOKEN);
      const left = again.ok ? missingIntents(again.flags) : stillMissing;
      if (!left.length) break;
      bad(`Still off: ${left.map((i) => i.name).join(', ')}`);
    }
  }
  ok('Message Content, Server Members and Presence are on');
  if (discord.ownerId) { v.BOT_OWNER_ID = discord.ownerId; ok(`You are the owner (${discord.ownerId})`); }

  // 2. Anthropic
  console.log(`\n${b('2/4 AI provider')}`);
  PROVIDERS.forEach((p, i) => console.log(`    ${i + 1}. ${p.label}`));
  const was = PROVIDERS.findIndex((p) => p.id === existing.get('DEFAULT_LLM_PROVIDER'));
  const pick = Number(await ask('  Which one?', String(was >= 0 ? was + 1 : 1)));
  const prov = PROVIDERS[Math.max(1, Math.min(PROVIDERS.length, pick || 1)) - 1];
  v.DEFAULT_LLM_PROVIDER = prov.id;
  console.log(`  Get a key at ${prov.where}\n`);
  for (;;) {
    v[prov.env] = await askSecret(`  ${prov.keyName}`, existing.get(prov.env));
    if (!v[prov.env]) continue;
    const env = Object.fromEntries(existing);
    let r = await checkProvider(prov.id, v[prov.env], env);
    // No credit: keep the key, wait for the top-up, check again.
    while (r.noCredit) {
      bad(r.why);
      await ask('  Press Enter once credit is added');
      r = await checkProvider(prov.id, v[prov.env], env);
    }
    if (r.ok) {
      if (r.model && prov.id === 'gemini') v.GEMINI_MODEL = r.model;
      if (r.model && prov.id === 'hermes') v.NOUS_MODEL = r.model;
      ok(r.busy ? 'Key works (the provider is busy right now, which is fine)' : `Key works${r.model ? ` with ${r.model}` : ''}`);
      break;
    }
    bad(r.why);
  }

  // 3. Connect
  console.log(`\n${b('3/4 Quidli Connect')}`);
  console.log('  Sign in at https://connect.quid.li, create an API key, and turn on Smart Send.\n');
  let chain = CHAINS.base;
  for (;;) {
    v.QUIDLI_API_KEY = await askSecret('  Connect API key', existing.get('QUIDLI_API_KEY'));
    if (!v.QUIDLI_API_KEY) continue;
    const me = await checkConnect(v.QUIDLI_API_KEY);
    if (!me.ok) { bad(me.why); continue; }
    ok(`Connected as ${me.username ?? 'your account'}`);

    console.log('\n  Which chain should the bot use when someone doesn\'t name one?');
    console.log('  People can still name any chain in a request.');
    const choices = await chainChoices(v.QUIDLI_API_KEY);
    choices.forEach((c, i) => console.log(`    ${i + 1}. ${c.name}${c.sponsored ? ' (gas is sponsored, recommended)' : ` (sender pays gas in ${c.native})`}`));
    const was = choices.findIndex((c) => c.id === findChain(existing.get('DEFAULT_CHAIN'))?.id);
    const pick = Number(await ask('  Which one?', String(was >= 0 ? was + 1 : 1)));
    const picked = choices[Math.max(1, Math.min(choices.length, pick || 1)) - 1];
    chain = CHAINS[picked.slug];
    v.DEFAULT_CHAIN = picked.slug;

    const r = chain.sponsored ? me : await checkConnect(v.QUIDLI_API_KEY, fetch, chain);
    if (!r.smartSendWallet) { bad('Smart Send looks off. Turn it on at https://connect.quid.li → Smart Send before the bot pays anyone.'); break; }
    if (chain.sponsored) ok(`Sends come from ${r.smartSendWallet}. Fund it with what you'll pay out (gas is sponsored on Base).`);
    else {
      ok(`Sends come from ${r.smartSendWallet} on ${chain.name}. Fund it with what you'll pay out.`);
      if (r.lowGas) bad(chain.id === CHAINS.solana.id
        ? 'It has under 0.01 SOL. Add some: each send costs a small fee, and paying someone a token for the first time costs about 0.002 SOL.'
        : `It has no ${chain.native}. ${gasNote(chain)}`);
    }
    break;
  }

  v.MASTER_ENCRYPTION_KEY = looksUnset(existing.get('MASTER_ENCRYPTION_KEY')) ? randomBytes(32).toString('hex') : existing.get('MASTER_ENCRYPTION_KEY');
  v.SYSTEM_PROMPT_FILE = 'labr-prompt.txt';
  v.OWNER_USES_HOST_KEY = existing.get('OWNER_USES_HOST_KEY') || 'false';

  if (existsSync(ENV_PATH)) {
    const bak = `${ENV_PATH}.backup-${Date.now()}`;
    copyFileSync(ENV_PATH, bak);
    console.log(`\n  (Your previous .env is saved as ${bak.split('/').pop()})`);
  }
  writeFileSync(ENV_PATH, renderEnv(v, existing), { mode: 0o600 });

  // Keys exported in the shell (e.g. by another tool) also reach the bot when
  // .env doesn't set them. Say so, so nothing is switched on by surprise.
  const fromShell = SHELL_KEYS.filter((k) => process.env[k] && !(k in v) && looksUnset(existing.get(k)));
  if (fromShell.length) {
    console.log(`\n  Note: ${fromShell.join(', ')} ${fromShell.length > 1 ? 'are' : 'is'} set in your shell, so the bot will use ${fromShell.length > 1 ? 'them' : 'it'} too.`);
    console.log('  To keep the bot off it, add an empty line for it to .env (e.g. BANKR_API_KEY=).');
  }

  // 4. Server
  console.log(`\n${b('4/4 Add the bot to your server')}`);
  console.log(`  Open this link and pick your server:\n\n  ${inviteUrl(discord.appId)}\n`);
  let guilds = await botGuilds(v.DISCORD_TOKEN);
  if (!guilds.length) {
    process.stdout.write('  Waiting for the bot to join');
    for (let i = 0; i < 100 && !guilds.length; i++) { await sleep(3000); process.stdout.write('.'); guilds = await botGuilds(v.DISCORD_TOKEN); }
    process.stdout.write('\n');
  }
  if (!guilds.length) {
    bad('The bot has not joined a server yet. Run `npm run setup` again after adding it; your answers are saved.');
  } else {
    let g = guilds[0];
    if (guilds.length > 1) {
      guilds.forEach((x, i) => console.log(`    ${i + 1}. ${x.name}`));
      const pick = Number(await ask('  Which server is Labr for?', '1'));
      g = guilds[Math.max(1, Math.min(guilds.length, pick || 1)) - 1];
    }
    v.DISCORD_ALLOWED_GUILDS = g.id;
    writeFileSync(ENV_PATH, renderEnv(v, existing), { mode: 0o600 });
    ok(`In "${g.name}". The bot will leave any other server it's added to.`);
  }

  console.log(`\n${b('Done.')} Settings are in .env (only on this machine).`);
  const hasPm2 = spawnSync('pm2', ['-v'], { stdio: 'ignore' }).status === 0;
  const start = (await ask(`  Start Labr now${hasPm2 ? ' with pm2 (keeps running after you close this)' : ''}? (Y/n)`, 'Y')).toLowerCase();
  if (start.startsWith('n')) {
    console.log(`\n  Start it later with ${hasPm2 ? '`pm2 start labr.config.cjs && pm2 save`' : '`npm start`'}.`);
  } else if (hasPm2) {
    spawnSync('pm2', ['start', 'labr.config.cjs'], { cwd: ROOT, stdio: 'inherit' });
    spawnSync('pm2', ['save'], { cwd: ROOT, stdio: 'inherit' });
    console.log('\n  Logs: `pm2 logs labr`');
  } else {
    console.log('\n  Starting in this window. Close it and the bot stops; for always-on, `npm i -g pm2` then `pm2 start labr.config.cjs`.\n');
    spawn('node', ['bot.js'], { cwd: ROOT, stdio: 'inherit' });
    return;
  }
  console.log(`\n  In your server, say ${b('@' + discord.name + ' help')}. Everyone links their own wallet by DMing the bot ${b('!connect <key>')}.\n`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((err) => { console.error(`\nSetup stopped: ${err.message}`); process.exit(1); });
}
